"""
Animation queue — which unanimated monsters to animate next, ordered by how
often a player will actually see them.

The roster mixes two art generations: 130 H3-animated sprites and ~390 static
DCSS tiles. Animating by CR or by biome finishes a tier, but a player's first
ten hours are spent on floors 1–6 across every theme, so the placeholders that
hurt most are the low-CR creatures on several themes' whitelists. This ranks
the static roster by an "exposure" estimate:

    exposure = sum over themes the creature can spawn in of
               weight(dungeon level its CR maps to)

where weight falls off with level (level 1 is seen by everyone, level 15 by
few), and a creature's level is the first anchor level whose CR reaches its
own (spawn_budget.json crAnchorLevels/crAnchorCRs — the same mapping the
spawner uses). Curated bosses (boss_encounters.json bossId) are listed
separately: they spawn once per run but are the most-looked-at sprite on the
floor, so they are worth animating regardless of exposure.

Writes docs/ANIMATION_QUEUE.md. Regenerate whenever monsters.json or the boss
table changes:

    python scripts/animation_queue.py
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
GAME = os.path.join(ROOT, "src", "game")
OUT = os.path.join(ROOT, "docs", "ANIMATION_QUEUE.md")


def load():
    with open(os.path.join(GAME, "monsters.json"), encoding="utf-8") as f:
        ms = json.load(f)
    ms = ms if isinstance(ms, list) else ms.get("monsters", ms)
    with open(os.path.join(GAME, "boss_encounters.json"), encoding="utf-8") as f:
        be = json.load(f)
    with open(os.path.join(GAME, "spawn_budget.json"), encoding="utf-8") as f:
        sb = json.load(f)
    anchors = list(zip(sb["crAnchorLevels"], sb["crAnchorCRs"]))
    return ms, be, anchors


def animated(m):
    a = m.get("animations") or {}
    return bool(a.get("idle") or a.get("attack"))


def level_for_cr(cr, anchors):
    for lvl, acr in anchors:
        if acr >= cr:
            return lvl
    return anchors[-1][0]


def level_weight(lvl):
    # Everyone sees floor 1; roughly half as many players see each 3 floors deeper.
    return 0.5 ** ((lvl - 1) / 3.0)


def cr_label(cr):
    return {0.125: "1/8", 0.25: "1/4", 0.5: "1/2"}.get(cr, str(int(cr)) if float(cr).is_integer() else str(cr))


def main():
    ms, be, anchors = load()
    boss_ids = {e["bossId"] for e in be if e.get("bossId")}
    boss_theme = {e["bossId"]: (e.get("theme"), e.get("level")) for e in be if e.get("bossId")}
    escort_ids = {}
    for e in be:
        for esc in e.get("escorts") or []:
            escort_ids.setdefault(esc["id"], []).append(f"{e.get('theme')} L{e.get('level')}")

    rows = []
    bosses = []
    orphans = []
    for m in ms:
        if animated(m):
            continue
        cr = float(m.get("cr", 0) or 0)
        lvl = level_for_cr(cr, anchors)
        themes = list(m.get("dungeons") or [])
        if m["id"] in boss_ids:
            t, l = boss_theme[m["id"]]
            bosses.append((t, l, m["id"], m.get("name"), cr_label(cr)))
            continue
        if not themes and m["id"] not in escort_ids:
            orphans.append((m["id"], m.get("name"), cr_label(cr)))
            continue
        exposure = sum(level_weight(lvl) for _ in themes)
        if m["id"] in escort_ids:
            exposure += 0.5 * len(escort_ids[m["id"]])
        rows.append((exposure, lvl, cr, m["id"], m.get("name"), themes, escort_ids.get(m["id"], [])))

    rows.sort(key=lambda r: (-r[0], r[1], r[3]))
    bosses.sort(key=lambda b: (b[1], b[0]))

    total = len(ms)
    n_anim = sum(1 for m in ms if animated(m))
    lines = []
    lines.append("# Animation queue\n")
    lines.append(f"Generated by `scripts/animation_queue.py`. {n_anim} of {total} monsters are animated; "
                 f"{len(rows)} static creatures spawn in rooms, {len(bosses)} static curated bosses, "
                 f"{len(orphans)} static records currently spawn nowhere.\n")
    lines.append("Ordered by **exposure** — how many themes a creature spawns in, weighted by how early "
                 "its CR puts it (floor 1 is seen by everyone; each three floors deeper halves the weight). "
                 "Animate from the top and each batch removes the most-seen placeholders first.\n")
    lines.append("## Room roster, by exposure\n")
    lines.append("| # | Creature | CR | Floor | Themes | Boss escort | Exposure |")
    lines.append("|--:|---|--:|--:|---|---|--:|")
    for i, (exp, lvl, cr, mid, name, themes, esc) in enumerate(rows, 1):
        lines.append(f"| {i} | {name} (`{mid}`) | {cr_label(cr)} | {lvl} | {', '.join(themes) or '—'} | {', '.join(esc) or '—'} | {exp:.2f} |")
    lines.append("\n## Curated bosses still static\n")
    lines.append("Seen once per run, but every eye is on them for the whole fight. Listed by the floor they guard.\n")
    lines.append("| Theme | Level | Boss | CR |")
    lines.append("|---|--:|---|--:|")
    for t, l, mid, name, cr in bosses:
        lines.append(f"| {t} | {l} | {name} (`{mid}`) | {cr} |")
    if orphans:
        lines.append("\n## Static records that spawn nowhere\n")
        lines.append("No theme whitelist and no boss escort slot — either a delisted creature or one waiting for a roster. "
                     "Not worth animating until something spawns it.\n")
        lines.append(", ".join(f"{n} (`{i}`, CR {c})" for i, n, c in sorted(orphans, key=lambda o: o[1] or "")))
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print(f"wrote {os.path.relpath(OUT, ROOT)}: {len(rows)} roster rows, {len(bosses)} bosses, {len(orphans)} orphans")
    return 0


if __name__ == "__main__":
    sys.exit(main())
