"""
Emit src/ui/ui_kit.css from the 9-slice sheets in src/ui/kit.

The kit replaces the CSS-drawn chrome (1px hairlines, inset bevels, the hard
3px pixel-theme borders at the bottom of game.css) with border-image slices
of real cut-stone art. This script owns the mapping from game selectors to
sheets so the CSS never carries hand-typed slice numbers: re-slice a sheet,
re-run this, and every panel using it follows.

Every rule is written with literal values and !important because the layer it
overrides (the pixel theme in game.css) is itself !important, and because
composing border-image-slice from custom properties fails to parse in some
engines (fallback is slice 100% -- the whole sheet drawn into each corner).

  python tools/ui_kit/build_kit_css.py
"""
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
KIT = os.path.join(ROOT, 'src', 'ui', 'kit')
OUT = os.path.join(ROOT, 'src', 'ui', 'ui_kit.css')

# The game's own drop shadow language: a hard 1-bit offset, no blur.
SHADOW = '4px 4px 0 rgba(0,0,0,.55)'


def meta(name):
    with open(os.path.join(KIT, name + '.json')) as f:
        return json.load(f)


def frame(name, scale, shadow=SHADOW, extra=''):
    """The border-image block for one sheet at an integer pixel scale."""
    t, r, b, l = meta(name)['slice']
    w = f'{t*scale}px {r*scale}px {b*scale}px {l*scale}px'
    return (
        f"  border-style:solid !important;\n"
        f"  border-width:{w} !important;\n"
        f"  border-image:url('./kit/{name}.png') {t} {r} {b} {l} fill / {w} repeat !important;\n"
        f"  border-radius:0 !important;\n"
        f"  image-rendering:pixelated;\n"
        + (f"  box-shadow:{shadow} !important;\n" if shadow is not None else '')
        + extra
    )


def rule(selectors, body):
    return ',\n'.join(selectors) + '{\n' + body + '}\n'


# ---------------------------------------------------------------------------
# Mapping. Grouped by sheet; each entry is (selectors, scale, extra css).
# ---------------------------------------------------------------------------

HUD_PANELS = [
    '.pframe', '#partyframes > *',
    '#initiative', '.init-wrap',
    '#logpanel', '#log-tray-btn',
    '#resources', '#floorbadge',
    '#cs-tooltip', '#questtracker',
    '.potion-btn',
]

MENU_PANELS = [
    '.cs-frame', '#charscreen .cs-frame', '.shop-frame', '.sc-card', '.fc-card',
    '#story-briefing .brief-card', '#boss-card .bc-card', '.ae-panel', '.roster-card',
    '.srd-skill-card', '.save-slot-card', '.cc-slot', '.facility-view-card',
    '.wm-story-card', '.wm-tavern-column', '.wm-sysmenu-section',
]

BUTTONS = [
    '.btn', '.ts-btn', '#resources button', '.mbar-btn', '.mode-toggle-btn',
    '#setup .actions button', '#shop-descend', '#wm-embark-btn', '.guild-subtab',
]
# small inline controls get the same slab at 1x so they stay small
SMALL_BUTTONS = ['.sort-btn', '.slot-reroll']
PRIMARY = ['.btn.primary', '.btn-primary', '#ts-new', '#shop-descend', '#wm-embark-btn',
           '#setup .actions button.primary']

TABS = ['.cs-tab', '.best-tab', '.chip', '.bag-tab', '.ai-preset', '.ai-chip']
SMALL_TABS = ['.log-tab', '.ps-chip', '.pt-pill', '.sk-ab-save', '.eq-cosmetic']
# every class the game uses to mean "this one is selected"
TAB_ON = ['.on', '.active', '.chosen', '.hot', '.prof']

# panels nested inside a menu: thin HUD rim, dark fill. 2x for cards, 1x for
# dense list rows where a 12px rim would eat the content.
SUBPANELS = ['.ai-card', '.ai-note', '.cs-stats', '.sk-choice', '.sk-xp-row',
             '.rail-hero', '.fam-form-card']
SUBPANELS_1X = ['.sk-skill', '.cs-feature']
# buttons whose text colour carries meaning (rarity) keep it: dark panel rim,
# not the ink-on-stone slab
COLOUR_BUTTONS = ['.sell-rarity-btn', '.ps-sell']

SLOTS = ['.eq-slot', '.bag-item']

# full-screen overlays that toggle .show — they get a short fade
OVERLAYS = ['#charscreen', '#shopscreen', '#worldmapscreen', '#setup', '#options-overlay',
            '#help-overlay', '#boss-card', '#story-briefing', '#wm-sysmenu', '#boss-intro']
# dialog / screen titles: the slab as a plaque at 2x; section headers at 1x
TITLES = ['.fc-title', '.opt-title', '.rs-title', '#setup h1', '.roster-title', '.ae-title',
          '.editor-title', '.sc-name']
SECTION_TITLES = ['.cs-stats h3', '.cs-bag h3', '.sk-abils h3', '.sk-skills h3', '.sk-subclass h3',
                  '.sk-unlocked h3', '.ai-presets h3', '.wm-shop-column h3', '.wm-tavern-column h3',
                  '.log-title', '.init-round', '.bulk-sell-title']


def build():
    css = [
        "/* ===== Dungeon Crawlers UI kit — cut-stone border-image chrome =====\n"
        "   GENERATED by tools/ui_kit/build_kit_css.py — edit the mapping there,\n"
        "   not this file. Loaded after game.css; remove the <link> to revert. */\n",
    ]

    # -- HUD panels: thin stone rim at 2x -----------------------------------
    # interiors: a near-flat slate tile (tools/ui_kit/make_bg_tile.py) instead
    # of solid black. HUD panels use the 90%-alpha copy so the dungeon still
    # shows through; menus are opaque with an inner vignette toward the rim.
    css.append(rule(HUD_PANELS, frame('frame_hud', 2, extra=(
        "  background:rgba(8,10,12,.9) url('./kit/bg_slate_hud.png') !important;\n"
        "  background-size:256px 256px !important;\n"))))
    # leader / concentration / hover used to recolour the hairline; the rim is
    # art now, so they become an outer ring in the same offset-shadow language.
    css.append(rule(['.pframe.leader'],
        f"  box-shadow:{SHADOW}, 0 0 0 2px rgba(193,169,116,.55) !important;\n"))
    css.append(rule(['.pframe.concentrating'],
        f"  box-shadow:{SHADOW}, 0 0 0 2px rgba(192,143,241,.6) !important;\n"))
    css.append(rule(['.pframe:hover'], "  filter:brightness(1.08);\n"))
    css.append(rule(['.pframe.down'], "  filter:grayscale(.8) brightness(.8);\n"))
    # #cs-tooltip had padding:0 with its own inner layout — give the rim room.
    css.append(rule(['#cs-tooltip'], "  background:var(--dc-panel-strong) !important;\n"))
    # potions are buttons in HUD clothing: physical press, no lift.
    css.append(rule(['.potion-btn:hover'], "  transform:none; filter:brightness(1.1);\n"))
    css.append(rule(['.potion-btn:active'], "  transform:translate(2px,2px); box-shadow:none !important;\n"))

    # -- Party-frame portrait: the hero's own sprite, floated beside name/sub --
    css.append(rule(['.pf-portrait'],
        "  float:left; width:32px; height:32px; margin:1px 8px 2px 0;\n"
        "  image-rendering:pixelated; background:#07080a;\n"
        "  border:2px solid; box-sizing:content-box;\n"        # colour set inline per class
        "  box-shadow:inset 0 0 0 1px rgba(0,0,0,.7), 2px 2px 0 rgba(0,0,0,.5);\n"))
    css.append(rule(['.pframe .pf-dot'], "  display:none;\n"))          # the ring carries the class colour now
    # HP bar tucks up beside the portrait, under the name (44px = 32 portrait
    # + 2x2 border + 8 margin); the rows after it clear the float.
    css.append(rule(['.pframe .pf-hpbar'], "  margin-left:44px;\n"))
    css.append(rule(['.pframe .pf-abils', '.pframe .pf-effects'], "  clear:both;\n"))
    css.append(rule(['.pframe.down .pf-portrait'], "  filter:grayscale(1) brightness(.6);\n"))

    # -- Party-frame bars: stone trough at 1x, fill shows through the groove --
    t, r, b, l = meta('bar')['slice']
    css.append(rule(['.pf-hpbar', '.pf-xpbar'],
        frame('bar', 1, shadow=None, extra=(
            "  background:#07080a !important;\n"
            "  overflow:visible !important;\n"))))
    # 22px tall: 11px of rim, 11px of groove. The overlay text spans the whole
    # bar, not just the groove, so it stays vertically centred on the rim.
    css.append(rule(['.pf-hpbar'], "  height:22px !important;\n"))
    css.append(rule(['.pf-hptext'],
        f"  top:{-t}px !important; bottom:{-b}px !important; line-height:22px !important;\n"))
    css.append(rule(['.pf-xpbar'], "  height:14px !important; margin-top:4px !important;\n"))
    css.append(rule(['.pf-hpfill', '.pf-xpfill', '.pf-tempfill'], "  border-radius:0 !important;\n"))

    # -- Menu / dialog frames: thin stone rim at 2x --------------------------
    css.append(rule(MENU_PANELS, frame('frame_menu', 2,
        shadow=f'inset 0 0 64px rgba(0,0,0,.6), {SHADOW}', extra=(
        "  background:#0d1014 url('./kit/bg_slate.png') !important;\n"
        "  background-size:256px 256px !important;\n"))))
    # the CSS corner brackets on .cs-frame are now redundant with real corners
    css.append(rule(['.cs-frame::before', '.cs-frame::after'], "  display:none !important;\n"))

    # -- Buttons: solid bevelled slab at 2x, dark ink text --------------------
    button_face = (
        "  background:transparent !important;\n"
        "  color:#14171c !important;\n"
        "  text-shadow:0 1px 0 rgba(255,255,255,.28) !important;\n"
        "  padding-top:0 !important; padding-bottom:0 !important;\n"
        "  line-height:1.15 !important;\n"
        "  transition:filter .1s !important;\n")
    css.append(rule(BUTTONS, frame('button_solid', 2, extra=button_face)))
    css.append(rule(SMALL_BUTTONS, frame('button_solid', 1, shadow='2px 2px 0 rgba(0,0,0,.5)', extra=button_face)))
    all_buttons = BUTTONS + SMALL_BUTTONS
    css.append(rule([s + ':hover:not(:disabled)' for s in all_buttons],
        "  filter:brightness(1.12); background:transparent !important; color:#14171c !important;\n"))
    css.append(rule([s + ':active:not(:disabled)' for s in all_buttons],
        "  transform:translate(2px,2px) !important; filter:brightness(.85); box-shadow:none !important;\n"))
    css.append(rule([s + ':disabled' for s in all_buttons],
        "  opacity:.5; filter:grayscale(1); background:transparent !important; color:#14171c !important;\n"))
    # primary actions: warm the stone rather than repaint it
    css.append(rule(PRIMARY,
        "  filter:sepia(.55) saturate(1.3) brightness(1.05);\n"
        "  background:transparent !important; color:#14171c !important;\n"))
    css.append(rule([s + ':hover:not(:disabled)' for s in PRIMARY],
        "  filter:sepia(.55) saturate(1.3) brightness(1.18); background:transparent !important; color:#14171c !important;\n"))

    # -- Tabs: same slab; the active one is lit stone, the rest are dimmed ----
    tab_face = (
        "  background:transparent !important;\n"
        "  color:#dfe3e8 !important;\n"
        "  filter:brightness(.62);\n"
        "  padding-top:0 !important; padding-bottom:0 !important;\n"
        "  transition:filter .1s !important;\n")
    css.append(rule(TABS, frame('button_solid', 2, shadow='2px 2px 0 rgba(0,0,0,.5)', extra=tab_face)))
    css.append(rule(SMALL_TABS, frame('button_solid', 1, shadow='2px 2px 0 rgba(0,0,0,.5)', extra=tab_face)))
    all_tabs = TABS + SMALL_TABS
    css.append(rule([s + ':hover' for s in all_tabs], "  filter:brightness(.8); color:#f2f4f6 !important;\n"))
    css.append(rule([s + '.on' for s in all_tabs] + [s + '.active' for s in all_tabs],
        "  filter:none; color:#14171c !important; background:transparent !important;\n"
        "  text-shadow:0 1px 0 rgba(255,255,255,.28) !important;\n"))

    # -- Sub-panels nested inside menus ---------------------------------------
    css.append(rule(SUBPANELS, frame('frame_hud', 2, shadow=None, extra=(
        "  background:var(--dc-panel) !important;\n"))))
    css.append(rule(SUBPANELS_1X, frame('frame_hud', 1, shadow=None, extra=(
        "  background:var(--dc-panel) !important;\n"))))
    # selected card: the fill was the only cue, and the rim rule above forces
    # the fill, so restate it here (rail hero, familiar form, etc.)
    css.append(rule([s + on for s in SUBPANELS + SUBPANELS_1X for on in TAB_ON],
        "  background:rgba(183,155,95,.14) !important;\n"))
    css.append(rule([s + ':hover' for s in ['.rail-hero', '.fam-form-card', '.sk-skill']],
        "  background:rgba(183,155,95,.08) !important;\n"))
    # the sk-xp-row / cs-stats had their own light padding; the 2x rim is 10-14px
    # so pull the inner padding back a notch to keep the row height sane
    css.append(rule(['.sk-xp-row'], "  padding:4px 10px !important;\n"))

    # -- Character-sheet XP track: the stone trough at 2x ----------------------
    css.append(rule(['.xp-track'], frame('bar', 2, shadow=None, extra=(
        "  background:#07080a !important; height:28px !important;\n"
        "  overflow:visible !important;\n"))))

    # -- Colour-carrying buttons: dark panel rim, text colour untouched --------
    css.append(rule(COLOUR_BUTTONS, frame('frame_hud', 1, shadow='2px 2px 0 rgba(0,0,0,.5)', extra=(
        "  background:var(--dc-panel) !important;\n"
        "  padding-top:0 !important; padding-bottom:0 !important;\n"))))
    css.append(rule([s + ':hover' for s in COLOUR_BUTTONS], "  filter:brightness(1.2);\n"))
    css.append(rule([s + ':active' for s in COLOUR_BUTTONS],
        "  transform:translate(1px,1px); box-shadow:none !important;\n"))

    # -- Cursors: bone arrow, gauntlet pointer, sword during combat -----------
    # game.css/styles.css say cursor:var(--cur-hand, pointer) wherever they
    # used to say pointer, so the fallback is the stock hand if this file is
    # ever removed. Hotspots come from tools/ui_kit/src -> cursors.json.
    with open(os.path.join(KIT, 'cursors.json')) as f:
        cur = json.load(f)
    def cursor(name, fallback):
        hx, hy = cur[name]['hotspot']
        return f"url('./kit/{name}.png') {hx} {hy}, {fallback}"
    css.append(rule([':root'],
        f"  --cur-arrow:{cursor('cursor_arrow', 'auto')};\n"
        f"  --cur-hand:{cursor('cursor_hand', 'pointer')};\n"
        f"  --cur-sword:{cursor('cursor_sword', 'crosshair')};\n"))
    css.append(rule(['html', 'body'], "  cursor:var(--cur-arrow);\n"))
    css.append(rule(['button', 'a', 'label', 'select', 'summary', '[role=button]', 'input[type=checkbox]', 'input[type=range]'],
        "  cursor:var(--cur-hand);\n"))
    css.append(rule(['button:disabled'], "  cursor:var(--cur-arrow);\n"))
    # over the dungeon canvas while a fight is on; the HUD keeps the arrow/hand
    css.append(rule(['body.dc-in-combat canvas'], "  cursor:var(--cur-sword);\n"))

    # -- Motion: overlays fade, framed panels rise ----------------------------
    # `from`-only keyframes interpolate to whatever transform the element
    # already has, so a frame positioned by translate() is not disturbed.
    css.append("@keyframes kit-fade{from{opacity:0}}\n"
               "@keyframes kit-rise{from{opacity:0;transform:translateY(14px)}}\n"
               "@keyframes kit-lowhp{0%,100%{outline-color:rgba(220,40,40,.15)}50%{outline-color:rgba(220,40,40,.95)}}\n")
    css.append(rule([o + '.show' for o in OVERLAYS], "  animation:kit-fade .16s ease-out;\n"))
    css.append(rule(MENU_PANELS, "  animation:kit-rise .22s cubic-bezier(.2,.7,.2,1) both;\n"))

    # -- Title plaques: the slab, dark ink, centred ----------------------------
    plaque = (
        "  background:transparent !important;\n"
        "  color:#14171c !important;\n"
        "  text-shadow:0 1px 0 rgba(255,255,255,.28) !important;\n"
        "  text-align:center !important;\n"
        "  display:block;\n")
    css.append(rule(TITLES, frame('button_solid', 2, shadow='3px 3px 0 rgba(0,0,0,.5)', extra=plaque + "  padding:2px 18px 4px !important;\n")))
    css.append(rule(SECTION_TITLES, frame('button_solid', 1, shadow='2px 2px 0 rgba(0,0,0,.5)', extra=plaque + "  padding:1px 10px 2px !important; margin-bottom:10px !important;\n")))

    # -- Floor banner: a hanging lintel that drops in -------------------------
    css.append(rule(['#banner'], frame('frame_hud', 3, extra=(
        "  background:rgba(8,10,12,.92) url('./kit/bg_slate_hud.png') !important;\n"
        "  background-size:256px 256px !important;\n"
        "  padding:10px 44px 14px !important;\n"
        "  transform:translate(-50%,-36px) scale(.98) !important;\n"
        "  transition:opacity .45s ease, transform .5s cubic-bezier(.2,.7,.2,1) !important;\n"))))
    css.append(rule(['#banner.show'], "  transform:translate(-50%,0) scale(1) !important;\n"))

    # -- Low-HP warning: a pulsing red outline on THAT hero's frame only.
    # Outline paints outside the box with no blur and no layout effect, so the
    # pulse costs a small repaint of one frame. (The full-screen blurred
    # vignette this replaced repainted the whole viewport every frame.)
    css.append(rule(['.pframe.low-hp'],
        "  outline:2px solid rgba(220,40,40,.15) !important; outline-offset:3px;\n"
        "  animation:kit-lowhp 1.2s ease-in-out infinite;\n"))

    # -- Item slots: recessed socket at 1x ------------------------------------
    css.append(rule(SLOTS, frame('slot', 1, shadow=None, extra=(
        "  background:#07080a !important;\n"
        "  overflow:visible !important;\n"))))
    # rarity used to be the 1px border colour (set inline). A pseudo-element
    # with border-color:inherit reads that same value and draws it as a ring
    # just inside the stone rim, so nothing in the JS has to change.
    css.append(rule(['.bag-item::after'],
        "  content:''; position:absolute; inset:0; pointer-events:none;\n"
        "  border:2px solid; border-color:inherit; opacity:.85;\n"))
    css.append(rule(['.bag-item:hover'], "  transform:none !important; filter:brightness(1.15);\n"))
    css.append(rule(['.bag-item.sel'],
        "  box-shadow:0 0 0 2px #c1a974, 0 0 12px rgba(193,169,116,.5) !important;\n"))

    with open(OUT, 'w', encoding='utf-8') as f:
        f.write(''.join(css))
    print('wrote', os.path.relpath(OUT, ROOT), len(''.join(css)), 'bytes')


if __name__ == '__main__':
    build()
