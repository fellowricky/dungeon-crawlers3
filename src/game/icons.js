/* Central registry for the generated pixel-art UI icons.
 *
 * Icons live at public/art/icons/<category>/<key>.png as 32px transparent PNGs.
 * They replace the emoji maps that were previously scattered across ui.js,
 * menus.js, entities.js, combat.js, skills.js and quest_events.js.
 *
 * There are TWO consumers with different needs, which is why this module exposes
 * two accessors rather than one:
 *
 *   iconHtml(cat, key)  -> an <img> string, for the DOM UI (party frames, menus,
 *                          tooltips, the combat log).
 *   iconImage(cat, key) -> a cached HTMLImageElement, for canvas work such as the
 *                          status billboards drawn above monsters in entities.js.
 *                          Returns null until the file has loaded, so callers must
 *                          keep their text fallback for the first frame.
 *
 * Emoji fallbacks are deliberately retained everywhere: a missing PNG degrades to
 * the old glyph instead of rendering an empty box.
 */

import { GLYPH_ICONS, GLYPH_SKIP } from './icon_glyphs.js';

const BASE = './art/icons';

/* 103 ability keys are the spell keys verbatim -- the ability entry for Fireball
 * is the same Fireball -- so they resolve to the spell art rather than duplicating
 * it. Generated by tools/icon_forge/build_manifest.mjs; kept inline so the game
 * has no build-time dependency on the forge. */
const ALIASES = {
  actionSurgeClass: 'ability/actionSurge',
  cunningActionClass: 'ability/cunningAction',
  wildShapeClass: 'ability/wildShape',
  burningHands: 'spell/dragonBreathSpell',
  moveMoonbeam: 'spell/moonbeam',
};

/* Categories searched, in order, when a caller does not name one. Ability before
 * spell so an aliased ability key still lands on its spell art via ALIASES. */
const SEARCH_ORDER = ['status', 'ability', 'spell', 'damage', 'class', 'ctype',
                      'reward', 'slot', 'facility', 'tech', 'rune', 'order',
                      'injury', 'qkind'];

/* Populated by setManifest() from the icon index so lookups never 404. Until it
 * is set, every path is treated as present and a missing file simply fails to
 * load, which the <img> onerror and the Image cache both tolerate. */
let known = null;

export function setManifest(paths) {
  known = paths instanceof Set ? paths : new Set(paths);
}

function has(path) {
  return known === null || known.has(path);
}

/** Resolve a logical key to "<category>/<key>", or null if nothing matches. */
export function iconPath(cat, key) {
  if (!key) return null;
  if (!cat) {
    if (ALIASES[key]) return has(ALIASES[key]) ? ALIASES[key] : null;
    for (const c of SEARCH_ORDER) {
      if (has(`${c}/${key}`)) return `${c}/${key}`;
    }
    return null;
  }
  if (cat === 'ability' && ALIASES[key]) {
    return has(ALIASES[key]) ? ALIASES[key] : null;
  }
  const direct = `${cat}/${key}`;
  if (has(direct)) return direct;
  // An ability that is really a spell resolves through the spell art.
  if (cat === 'ability' && has(`spell/${key}`)) return `spell/${key}`;
  return null;
}

export function iconUrl(cat, key) {
  const p = iconPath(cat, key);
  return p ? `${BASE}/${p}.png` : null;
}

/**
 * An <img> for DOM UI. `fallback` is the old emoji and is returned verbatim when
 * no PNG exists, so partially-migrated screens keep working.
 */
export function iconHtml(cat, key, fallback = '', opts = {}) {
  const url = iconUrl(cat, key);
  if (!url) return fallback;
  const cls = opts.cls ? ` ${opts.cls}` : '';
  const title = opts.title ? ` title="${String(opts.title).replace(/"/g, '&quot;')}"` : '';
  const size = opts.size ? ` style="width:${opts.size}px;height:${opts.size}px"` : '';
  return `<img class="ico${cls}" src="${url}" alt=""${title}${size}>`;
}

/* Longest-first alternation so a glyph with a variation selector ("❄️") is
   matched before its bare form ("❄"), which would otherwise leave a stray
   selector behind as a tofu box. */
const GLYPH_RE = new RegExp(
  Object.keys(GLYPH_ICONS)
    .sort((a, b) => b.length - a.length)
    .map(g => g.replace(/[.*+?^${}()|[\]\\]/g, '\\$&'))
    .join('|'),
  'g');

/**
 * Swap emoji in a string for their generated icons.
 *
 * Only safe on text bound for innerHTML. The floating combat text renderer walks
 * the string grapheme by grapheme and paints it onto a canvas, so running this on
 * anything headed there would draw the markup literally.
 */
export function iconifyText(str) {
  if (!str || typeof str !== 'string') return str;

  const swap = text => text.replace(GLYPH_RE, glyph => {
    if (GLYPH_SKIP.has(glyph)) return glyph;
    const path = GLYPH_ICONS[glyph];
    if (!path || !has(path)) return glyph;
    return `<img class="ico ico-inline" src="${BASE}/${path}.png" alt="${glyph}">`;
  });

  if (!str.includes('<')) return swap(str);
  /* Some callers hand formatLogMessage a string that already contains markup.
     Substituting blindly could drop an <img> inside an attribute (a title with
     an emoji in it) and produce broken HTML, so only the text between tags is
     touched. Odd indices of this split are the tags themselves. */
  return str.split(/(<[^>]*>)/g)
    .map((part, i) => (i % 2 ? part : swap(part)))
    .join('');
}

/* Canvas path: entities.js draws status billboards into a texture, where an
 * <img> tag is useless. Images are cached and decoded once; the first call
 * returns null and the caller falls back to text until onload fires. */
const imgCache = new Map();

export function iconImage(cat, key) {
  const url = iconUrl(cat, key);
  if (!url) return null;
  let entry = imgCache.get(url);
  if (!entry) {
    const img = new Image();
    entry = { img, ready: false };
    img.onload = () => { entry.ready = true; };
    img.onerror = () => { entry.failed = true; };
    img.src = url;
    imgCache.set(url, entry);
  }
  return entry.ready ? entry.img : null;
}

/** Warm the cache for icons that will be drawn to canvas, to avoid a first-use pop. */
export function preloadIcons(pairs) {
  for (const [cat, key] of pairs) iconImage(cat, key);
}

/**
 * Load the generated index so iconPath() can tell a missing icon from a present
 * one without a network round trip. Safe to skip: without it every lookup is
 * optimistic and a missing file just fails to render.
 */
export async function loadIconManifest() {
  try {
    const res = await fetch(`${BASE}/index.json`);
    if (!res.ok) return false;
    setManifest(await res.json());
    return true;
  } catch {
    return false;
  }
}
